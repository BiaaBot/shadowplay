  // STEP 3
  // =====================================================

  //Function that creates the interface for Step 3, where the user can edit the generated storyline.
  function viewStep3() {
    const status = el("div", { class: "small" });

    const loglineBox = el("textarea", { class: "mono" });
    loglineBox.value = state.storyline?.logline || "";

    // Prepares UI controls for each act and stores on the act object
    state.storyline.acts.forEach((act) => {
      if (!act._ui) {
        const title = el("input", { type: "text" });
        title.value = act.title || "";

        const summary = el("textarea");
        summary.value = act.summary || "";

        const beats = el("textarea", { class: "mono" });
        beats.value = (act.beats || []).join("\n");

        act._ui = { title, summary, beats };
      }
    });

    function syncEdits() {
      state.storyline.logline = loglineBox.value.trim();

      state.storyline.acts.forEach((act) => {
        const ui = act._ui;
        act.title = ui.title.value.trim();
        act.summary = ui.summary.value.trim();
        act.beats = ui.beats.value
          .split("\n")
          .map((s) => s.trim())
          .filter(Boolean);
      });
    }

    //Creates the tabs for the logline and each act, and the content area where the user can edit the log line and each act's details. 
    const tabs = el("div", { class: "tabs" });
    const contentArea = el("div", { class: "tab-content" });

    let activeTab = 0; // 0 = logline, 1..n = acts

    // Switches the active tab and refreshes the visible content.
    function setActiveTab(i) {
      activeTab = i;
      Array.from(tabs.children).forEach((b, idx) => {
        if (idx === i) b.classList.add("active");
        else b.classList.remove("active");
      });
      renderActive();
    }

    //Renders the selected tab's content
    function renderActive() {
      contentArea.innerHTML = "";                                   //Removes the previously visible tab content

      if (activeTab === 0) {
        contentArea.appendChild(field("Logline", loglineBox));
        return;
      }

      const actIndex = activeTab - 1;
      const act = state.storyline.acts[actIndex];
      const ui = act._ui;

      contentArea.appendChild(el("hr"));

      contentArea.appendChild(field("Title", ui.title));
      contentArea.appendChild(field("Summary", ui.summary));
      contentArea.appendChild(field("Beats", ui.beats));

      const regen = el("button", {
        class: "secondary primary-button",
        type: "button",
        text: "Regenerate this act"
      });

      regen.addEventListener("click", async () => {                 //Starts the act regeneration
        try {
          regen.disabled = true;
          status.textContent = `Regenerating Act ${actIndex + 1}…`;

          syncEdits();

          const updated = await apiPost("/api/act/regenerate", {
            prompt: state.promptText,
            storyline: state.storyline,
            actIndex
          });

          state.storyline.acts[actIndex] = updated.act;            //Replaces only the selected act with the newly generated one

          const a = state.storyline.acts[actIndex];                //Rebuilds the act's UI
          a._ui = null;

          if (!a._ui) {                                            //Re-prepares UI controls
            const title = el("input", { type: "text" });
            title.value = a.title || "";

            const summary = el("textarea");
            summary.value = a.summary || "";

            const beats = el("textarea", { class: "mono" });
            beats.value = (a.beats || []).join("\n");

            a._ui = { title, summary, beats };
          }

          renderTabs();
          setActiveTab(activeTab);
        } catch (e) {
          alert(e.message);
        } finally {
          regen.disabled = false;
          status.textContent = "";
        }
      });

      contentArea.appendChild(el("div", { class: "actions" }, [regen]));
    }


    function renderTabs() {
      tabs.innerHTML = "";
      const logBtn = el("button", { class: "tab-button", type: "button", text: "Logline" });
      logBtn.addEventListener("click", () => setActiveTab(0));
      tabs.appendChild(logBtn);

      state.storyline.acts.forEach((act, idx) => {
        const b = el("button", { class: "tab-button", type: "button", text: `Act ${idx + 1}` });
        b.addEventListener("click", () => setActiveTab(idx + 1));
        tabs.appendChild(b);
      });

      //Set initial active
      setActiveTab(activeTab);
    }

    const nextBtn = el("button", { class: "next-top primary-button", text: "Next → Generate Full Fairytale" });

    //Calls POST /api/fairytale with the prompt, the storyline and the current default word count to generate the full story in prose
    nextBtn.addEventListener("click", async () => {
      try {
        nextBtn.disabled = true;
        status.textContent = "Generating fairytale with OpenAI…";

        syncEdits();

        const data = await apiPost("/api/fairytale", {
          prompt: state.promptText,
          storyline: state.storyline,
          wordCount: state.wordCount
        });

        state.fairytaleText = data.text || "";

        //Displays the Step 4 interface
        setViewWithHome(viewStep4());
      } catch (e) {
        alert(e.message);
      } finally {
        nextBtn.disabled = false;
        status.textContent = "";
      }
    });

    renderTabs();

    return el("div", { class: "step1-page" }, [
      el("div", { class: "card" }, [
        el("h1", { text: "Step 3 — Edit Storyline" }),

        tabs,
        contentArea,

        el("div", { class: "actions" }, [
          el("button", { class: "back-button primary-button", type: "button", text: "← Back", onclick: () => setViewWithHome(viewStep2()) }),

          nextBtn
        ]),

        status
      ])
    ]);
  }

