    //Computes the smallest rectangle that covers both input bounds.
    function getUnionBounds(
      first,
      second
    ) {
      const minX =
        Math.min(
          first.x,
          second.x
        );

      const minY =
        Math.min(
          first.y,
          second.y
        );

      const maxX =
        Math.max(
          first.x +
          first.width,

          second.x +
          second.width
        );

      const maxY =
        Math.max(
          first.y +
          first.height,

          second.y +
          second.height
        );

      return {
        x:
          minX,

        y:
          minY,

        width:
          maxX - minX,

        height:
          maxY - minY
      };
    }

    //This function prepares the final physical character file
    async function createScaledCharacterSvg(
      svgText,
      filename,
      sizeClass
    ) {
      if (!svgText) {
        throw new Error(
          "This character SVG has not been generated."
        );
      }

      const {
        svg
      } = parseSvg(
        svgText
      );

      const measurement =
        mountSvgForMeasurement(
          svg
        );

      try {
        const measuredSvg =
          measurement.svg;

        const figure =
          measuredSvg.querySelector(
            "#character-figure"
          );

        const pedestal =
          measuredSvg.querySelector(
            "#character-pedestal"
          );

        if (!figure) {
          throw new Error(
            "The character figure group was not found."
          );
        }

        if (!pedestal) {
          throw new Error(
            "The character pedestal was not found."
          );
        }

        const figureBounds =
          figure.getBBox();

        const pedestalBounds =
          pedestal.getBBox();

        if (
          figureBounds.width <= 0 ||
          figureBounds.height <= 0
        ) {
          throw new Error(
            "The character figure could not be measured."
          );
        }

        const targetFigureHeightMm =
          sizeClass === "adult"
            ? 39
            : 26;

        const combinedBounds =
          getUnionBounds(
            figureBounds,
            pedestalBounds
          );

        const paddingMm =
          0.5;

        const unitsPerMm =
          figureBounds.height /
          targetFigureHeightMm;

        const paddingUnits =
          paddingMm *
          unitsPerMm;

        const croppedBounds = {
          x:
            combinedBounds.x -
            paddingUnits,

          y:
            combinedBounds.y -
            paddingUnits,

          width:
            combinedBounds.width +
            paddingUnits * 2,

          height:
            combinedBounds.height +
            paddingUnits * 2
        };

        const physicalWidthMm =
          croppedBounds.width /
          unitsPerMm;

        const physicalHeightMm =
          croppedBounds.height /
          unitsPerMm;

        measuredSvg.setAttribute(
          "viewBox",
          [
            croppedBounds.x,
            croppedBounds.y,
            croppedBounds.width,
            croppedBounds.height
          ].join(" ")
        );

        measuredSvg.setAttribute(
          "width",
          `${physicalWidthMm}mm`
        );

        measuredSvg.setAttribute(
          "height",
          `${physicalHeightMm}mm`
        );

        measuredSvg.setAttribute(
          "preserveAspectRatio",
          "xMidYMid meet"
        );

        measuredSvg.setAttribute(
          "xmlns",
          "http://www.w3.org/2000/svg"
        );

        weldCharacterAndPedestalForExport(
          measuredSvg
        );

        const finalSvgText =
          serializeSvg(
            measuredSvg
          );

        downloadSvgText(
          finalSvgText,
          filename
        );

        return {
          sizeClass,
          targetFigureHeightMm,
          physicalWidthMm,
          physicalHeightMm
        };

      } finally {
        measurement.container.remove();
      }
    }

