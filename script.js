    //Builds and saves a text document as a PDF with simple formatting.
    function downloadTextAsPdf({
      text,
      title,
      filename,
      subtitle = ""
    }) {
      const cleanText = String(text || "").trim();

      if (!cleanText) {
        alert(
          `The ${title.toLowerCase()} is empty. Please generate or enter some text before downloading it.`
        );
        return;
      }

      if (!window.jspdf?.jsPDF) {
        alert(
          "The PDF library could not be loaded. Please check your internet connection and reload the page."
        );
        return;
      }

      const { jsPDF } = window.jspdf;

      const pdf = new jsPDF({
        orientation: "portrait",
        unit: "mm",
        format: "a4"
      });

      const pageWidth =
        pdf.internal.pageSize.getWidth();

      const pageHeight =
        pdf.internal.pageSize.getHeight();

      const marginLeft = 20;
      const marginRight = 20;
      const marginTop = 20;
      const marginBottom = 20;

      const usableWidth =
        pageWidth -
        marginLeft -
        marginRight;

      const lineHeight = 6;

      let currentY = marginTop;

      function addNewPage() {
        pdf.addPage();
        currentY = marginTop;
      }

      function ensureSpace(requiredHeight = lineHeight) {
        if (
          currentY + requiredHeight >
          pageHeight - marginBottom
        ) {
          addNewPage();
        }
      }

      //PDF title
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(18);

      pdf.text(
        title,
        pageWidth / 2,
        currentY,
        {
          align: "center"
        }
      );

      currentY += 10;

      //Optional subtitle
      if (subtitle) {
        pdf.setFont("helvetica", "normal");
        pdf.setFontSize(10);
        pdf.setTextColor(100);

        const subtitleLines =
          pdf.splitTextToSize(
            subtitle,
            usableWidth
          );

        subtitleLines.forEach((line) => {
          ensureSpace(lineHeight);

          pdf.text(
            line,
            pageWidth / 2,
            currentY,
            {
              align: "center"
            }
          );

          currentY += 5;
        });

        currentY += 5;
      }

      pdf.setTextColor(0);
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(11);

      const paragraphs =
        cleanText.split(/\n/);

      paragraphs.forEach((paragraph) => {
        const paragraphText =
          paragraph.trim();

        if (!paragraphText) {
          ensureSpace(lineHeight);
          currentY += lineHeight;
          return;
        }

        const wrappedLines =
          pdf.splitTextToSize(
            paragraphText,
            usableWidth
          );

        wrappedLines.forEach((line) => {
          ensureSpace(lineHeight);

          pdf.text(
            line,
            marginLeft,
            currentY
          );

          currentY += lineHeight;
        });

        currentY += 2;
      });

      pdf.save(filename);
    }

