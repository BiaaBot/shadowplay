  //Converts raw SVG XML into a browser loadable data URL
  function svgTextToBrowserDataUrl(
    svgText
  ) {
    return (
      "data:image/svg+xml;charset=utf-8," +
      encodeURIComponent(svgText)
    );
  }

  // Parses a string of SVG markup and validates that it contains a real SVG document.
  function parseSvg(svgText) {
    //Creates a browser XML parser
    const parser =
      new DOMParser();

    //Converts the SVG text into a DOM document
    const documentNode =
      parser.parseFromString(
        svgText,
        "image/svg+xml"
      );

    //Throws an error if a <parseerror> element is detected
    const parserError =
      documentNode.querySelector(
        "parsererror"
      );

    if (parserError) {
      throw new Error(
        "The generated SVG could not be parsed."
      );
    }

    const svg =
      documentNode.documentElement;

    //Ensures the content has <svg> as its root
    if (
      !svg ||
      svg.tagName
        .toLowerCase() !== "svg"
    ) {
      throw new Error(
        "The generated content is not a valid SVG."
      );
    }

    return {
      documentNode,
      svg
    };
  }

  //Does the reverse of parseSvg(), converting a modified SVG DOM element back into SVG text.
  function serializeSvg(svg) {
    return new XMLSerializer()
      .serializeToString(svg);
  }

  //Downloads an SVG string as a file
  function downloadSvgText(
    svgText,
    filename
  ) {
    const blob =
      new Blob(
        [svgText],
        {
          type:
            "image/svg+xml;charset=utf-8"
        }
      );

    const url =                                           //Creates a temporary browser URL for the Blob
      URL.createObjectURL(blob);

    const link =
      document.createElement("a");

    link.href = url;
    link.download = filename;

    document.body.appendChild(
      link
    );

    link.click();
    link.remove();

    setTimeout(() => {
      URL.revokeObjectURL(url);
    }, 1000);
  }

  //Creates a filename safe identifier
  function makeSafeFilename(text) {
    return String(
      text || "asset"
    )
      .toLowerCase()
      .trim()
      .replace(
        /[^a-z0-9]+/g,
        "-"
      )
      .replace(
        /^-+|-+$/g,
        ""
      );
  }

  // Reads the SVG viewBox or fallback dimensions so the element can be positioned and scaled correctly.
  function getSvgViewBox(svg) {
    const viewBox =
      svg.viewBox?.baseVal;

    if (
      viewBox &&
      viewBox.width > 0 &&
      viewBox.height > 0
    ) {
      return {
        x:
          viewBox.x,

        y:
          viewBox.y,

        width:
          viewBox.width,

        height:
          viewBox.height
      };
    }

    const width =
      Number.parseFloat(
        svg.getAttribute(
          "width"
        )
      );

    const height =
      Number.parseFloat(
        svg.getAttribute(
          "height"
        )
      );

    if (
      Number.isFinite(width) &&
      width > 0 &&
      Number.isFinite(height) &&
      height > 0
    ) {
      return {
        x: 0,
        y: 0,
        width,
        height
      };
    }

    throw new Error(
      "The SVG has no valid viewBox or dimensions."
    );
  }

  // Mounts an SVG in an offscreen container so its dimensions can be measured safely.
  function mountSvgForMeasurement(
    svg
  ) {
    const container =
      document.createElement("div");

    container.style.position =
      "fixed";

    container.style.left =
      "-100000px";

    container.style.top =
      "-100000px";

    container.style.width =
      "2000px";

    container.style.height =
      "2000px";

    container.style.visibility =
      "hidden";

    container.style.pointerEvents =
      "none";

    document.body.appendChild(
      container
    );

    const importedSvg =
      document.importNode(
        svg,
        true
      );

    container.appendChild(
      importedSvg
    );

    return {
      container,
      svg:
        importedSvg
    };
  }

  //This function performs a geometric Boolean union between the character silhouette and the pedestal, turning them into one unified black vector shape.
  function weldCharacterAndPedestalForExport(
    svg
  ) {
    if (!window.paper) {
      throw new Error(
        "Paper.js was not loaded. Check the Paper.js script tag in index.html."                //Function depends on Paper.js being loaded in index.html
      );
    }

    const figure =
      svg.querySelector(
        "#character-figure"
      );

    const pedestal =
      svg.querySelector(
        "#character-pedestal"
      );

    if (!figure) {
      throw new Error(
        "The character figure could not be found before welding."
      );
    }

    if (!pedestal) {
      throw new Error(
        "The character pedestal could not be found before welding."
      );
    }

    const paperScope =
      new paper.PaperScope();

    const canvas =
      document.createElement(
        "canvas"
      );

    canvas.width = 1;
    canvas.height = 1;

    paperScope.setup(
      canvas
    );

    try {
      const sourceGroup =
        svg.ownerDocument
          .createElementNS(
            "http://www.w3.org/2000/svg",
            "g"
          );

      sourceGroup.appendChild(
        figure.cloneNode(true)
      );

      sourceGroup.appendChild(
        pedestal.cloneNode(true)
      );

      const imported =
        paperScope.project.importSVG(
          sourceGroup,
          {
            expandShapes: true,
            applyMatrix: true,
            insert: true
          }
        );

      const pathItems =
        imported.getItems({
          recursive: true,

          match: (item) => {
            const isPathItem =
              item instanceof
              paperScope.Path ||
              item instanceof
              paperScope.CompoundPath;

            const isCompoundChild =
              item.parent instanceof
              paperScope.CompoundPath;

            return (
              isPathItem &&
              !isCompoundChild
            );
          }
        });

      if (
        pathItems.length === 0
      ) {
        throw new Error(
          "No vector paths were found in the character SVG."
        );
      }

      let combined =
        pathItems[0];

      for (
        let index = 1;
        index < pathItems.length;
        index += 1
      ) {
        combined =
          combined.unite(
            pathItems[index],
            {
              insert: false
            }
          );
      }

      combined.fillColor =
        new paperScope.Color(
          "#000000"
        );

      combined.strokeColor =
        null;

      combined.name =
        "character-cut-shape";

      const exportedNode =
        combined.exportSVG({
          asString: false,
          matchShapes: false,
          reduceAttributes: false
        });

      exportedNode.setAttribute(
        "id",
        "character-cut-shape"
      );

      exportedNode.setAttribute(
        "fill",
        "#000000"
      );

      exportedNode.setAttribute(
        "stroke",
        "none"
      );

      figure.remove();
      pedestal.remove();

      const finalNode =
        svg.ownerDocument.importNode(
          exportedNode,
          true
        );

      svg.appendChild(
        finalNode
      );

      return svg;

    } finally {
      paperScope.project.clear();
    }
  }

  // Adds a pedestal beneath the character figure in the SVG and prepares it for export.
  async function addCharacterPedestalToSvg(
    svgText
  ) {
    const {
      svg
    } = parseSvg(
      svgText
    );

    if (
      svg.querySelector(
        "#character-pedestal"
      )
    ) {
      const unchanged =
        serializeSvg(svg);

      return {
        svgText:
          unchanged,

        dataUrl:
          svgTextToBrowserDataUrl(
            unchanged
          )
      };
    }

    const measurement =
      mountSvgForMeasurement(
        svg
      );

    try {
      const measuredSvg =
        measurement.svg;

      const viewBox =
        getSvgViewBox(
          measuredSvg
        );

      const figureGroup =
        measuredSvg.ownerDocument
          .createElementNS(
            "http://www.w3.org/2000/svg",
            "g"
          );

      figureGroup.setAttribute(
        "id",
        "character-figure"
      );

      const children =
        Array.from(
          measuredSvg.children
        );

      children.forEach(
        (child) => {
          const tag =
            child.tagName
              .toLowerCase();

          if (
            tag === "defs" ||
            tag === "metadata" ||
            tag === "title" ||
            tag === "desc"
          ) {
            return;
          }

          figureGroup.appendChild(
            child
          );
        }
      );

      measuredSvg.appendChild(
        figureGroup
      );

      const figureBounds =
        figureGroup.getBBox();

      if (
        figureBounds.width <= 0 ||
        figureBounds.height <= 0
      ) {
        throw new Error(
          "The character SVG contains no measurable figure."
        );
      }

      const pedestalWidth =                           //25% of original canvas
        viewBox.width * 0.25;

      const pedestalHeight =                          //height = 18% of original canvas
        viewBox.height * 0.18;

      const pedestalX =
        figureBounds.x +
        figureBounds.width / 2 -
        pedestalWidth / 2;

      const overlap =                                //The slight overlap makes sure the figure connects to the pedestal
        viewBox.height * 0.03;

      const figureBottom =
        figureBounds.y +
        figureBounds.height;

      const pedestalY =
        figureBottom -
        overlap;

      const pedestal =
        measuredSvg.ownerDocument
          .createElementNS(
            "http://www.w3.org/2000/svg",
            "rect"
          );

      pedestal.setAttribute(
        "id",
        "character-pedestal"
      );

      pedestal.setAttribute(
        "x",
        String(pedestalX)
      );

      pedestal.setAttribute(
        "y",
        String(pedestalY)
      );

      pedestal.setAttribute(
        "width",
        String(pedestalWidth)
      );

      pedestal.setAttribute(
        "height",
        String(pedestalHeight)
      );

      pedestal.setAttribute(
        "rx",
        String(
          pedestalHeight / 5
        )
      );

      pedestal.setAttribute(
        "ry",
        String(
          pedestalHeight / 5
        )
      );

      pedestal.setAttribute(
        "fill",
        "#000000"
      );

      measuredSvg.insertBefore(
        pedestal,
        figureGroup
      );

      const padding =
        viewBox.height * 0.015;

      const minX =
        Math.min(
          viewBox.x,
          pedestalX - padding
        );

      const minY =
        Math.min(
          viewBox.y,
          figureBounds.y - padding
        );

      const maxX =
        Math.max(
          viewBox.x +
          viewBox.width,

          pedestalX +
          pedestalWidth +
          padding
        );

      const maxY =
        Math.max(
          viewBox.y +
          viewBox.height,

          pedestalY +
          pedestalHeight +
          padding
        );

      measuredSvg.setAttribute(
        "viewBox",
        [
          minX,
          minY,
          maxX - minX,
          maxY - minY
        ].join(" ")
      );

      measuredSvg.removeAttribute(
        "width"
      );

      measuredSvg.removeAttribute(
        "height"
      );

      const finalSvgText =
        serializeSvg(
          measuredSvg
        );

      return {
        svgText:
          finalSvgText,

        dataUrl:
          svgTextToBrowserDataUrl(
            finalSvgText
          )
      };

    } finally {
      measurement.container.remove();
    }
  }


  // Generates an asset image for the given asset definition and prepares it for display.
  async function generateAsset(
    asset,
    options = {}
  ) {
    const {
      force = false
    } = options;

    const choice =
      state.assetChoices[
      asset.key
      ];

    if (!choice) {
      throw new Error(
        "Missing asset choice state."
      );
    }

    const img =
      await apiPost(
        "/api/puppets/image",
        {
          kind: asset.kind,

          key: asset.key,

          prompt:
            choice.promptText ||
            asset.prompt ||
            "",

          force
        }
      );

    if (
      asset.kind === "character" &&
      img?.svgText
    ) {
      const characterSvg =
        await addCharacterPedestalToSvg(
          img.svgText
        );

      img.svgText =
        characterSvg.svgText;

      img.dataUrl =
        characterSvg.dataUrl;
    }

    state.puppetImages[
      asset.key
    ] = img;
  }

