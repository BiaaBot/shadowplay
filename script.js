  //Collects background assets grouped by their key from the puppet plan.
  function getBackgroundAssets() {
    const backgroundMap = new Map();

    for (const act of state.puppetPlan?.acts || []) {
      const bg = act.background;

      if (!bg?.key) continue;

      if (!backgroundMap.has(bg.key)) {
        backgroundMap.set(bg.key, {
          kind: "background",
          key: bg.key,
          title: bg.key,
          prompt: bg.prompt || "",
          acts: []
        });
      }

      backgroundMap.get(bg.key).acts.push({
        actIndex: act.actIndex,
        actTitle: act.actTitle
      });
    }

    return [...backgroundMap.values()].map((bg) => ({
      ...bg,
      title:
        bg.acts.length === 1
          ? `Background — Act ${bg.acts[0].actIndex + 1}`
          : `Background — Acts ${bg.acts
            .map((a) => a.actIndex + 1)
            .join(", ")}`
    }));
  }

  //Collects character assets grouped by their key from the puppet plan.
  function getCharacterAssets() {
    const charactersMap = new Map();

    for (const act of state.puppetPlan?.acts || []) {
      for (const ch of act.characters || []) {
        if (!ch?.key) continue;

        if (!charactersMap.has(ch.key)) {
          charactersMap.set(ch.key, {
            kind: "character",
            key: ch.key,
            title: ch.name || ch.key,
            name: ch.name || ch.key,
            prompt: ch.prompt || "",
            acts: []
          });
        }

        charactersMap.get(ch.key).acts.push({
          actIndex: act.actIndex,
          actTitle: act.actTitle
        });
      }
    }

    return [...charactersMap.values()];
  }

  //Returns one array containing backgrounds first and characters second.
  function getAllAssets() {
    return [
      ...getBackgroundAssets(),
      ...getCharacterAssets()
    ];
  }

  // Ensures each asset from the current plan has a default editable prompt state.
  function ensureAssetChoices() {
    for (const asset of getAllAssets()) {
      if (!state.assetChoices[asset.key]) {
        state.assetChoices[asset.key] = {
          promptText: asset.prompt || ""
        };
      }
    }
  }

